#!/usr/bin/env python3
"""Sign Fit Dashboard firmware for over-the-air updates (see FitDashboard/ota.h).

  python3 tools/ota_release.py keygen
      Creates the signing key (once) and writes FitDashboard/ota_pubkey.h.
      The private key stays outside the repository; back it up. Without it no
      device that runs this firmware can be updated over the air any more.

  python3 tools/ota_release.py build
      Compiles a release binary with arduino-cli and -DFITDASH_RELEASE (no
      secrets.h inside), then runs "release" on it. arduino-cli: $ARDUINO_CLI
      or PATH; extra arguments for it (e.g. --config-file) in $ARDUINO_CLI_ARGS.

  python3 tools/ota_release.py release <FitDashboard.ino.bin>
      Refuses binaries that contain values from secrets.h. Reads FW_VERSION/FW_BUILD and OTA_MANIFEST_URL from config.h, signs the
      binary and writes release/FitDashboard.bin + release/version.json.
      Then upload both files to a GitHub release with the tag v<FW_VERSION>.

Key location: $FITDASH_OTA_KEY or ~/.config/fitdashboard/ota_signing_key.pem
"""
import base64
import hashlib
import json
import os
import re
import shlex
import shutil
import subprocess
import sys

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKETCH = os.path.join(ROOT, "FitDashboard")
OUT = os.path.join(ROOT, "release")
KEY = os.environ.get("FITDASH_OTA_KEY") or os.path.expanduser("~/.config/fitdashboard/ota_signing_key.pem")
FQBN = "esp32:esp32:XIAO_ESP32S3_Plus:PSRAM=opi,PartitionScheme=app3M_fat9M_16MB,FlashSize=16M"
APP_PARTITION = 0x300000  # app0/app1 in "16M Flash (3MB APP/9.9MB FATFS)"


def define(name):
    text = open(os.path.join(SKETCH, "config.h"), encoding="utf-8").read()
    m = re.search(r"#define\s+" + name + r'\s+("([^"]*)"|(\d+))', text)
    if not m:
        sys.exit(f"{name} fehlt in config.h")
    return m.group(2) if m.group(2) is not None else int(m.group(3))


def keygen():
    if os.path.exists(KEY):
        sys.exit(f"Schlüssel existiert schon: {KEY} (nicht überschrieben)")
    os.makedirs(os.path.dirname(KEY), exist_ok=True)
    key = ec.generate_private_key(ec.SECP256R1())
    pem = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())
    fd = os.open(KEY, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(pem)
    pub = key.public_key().public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo).decode()
    lines = "".join(f'  "{line}\\n"\n' for line in pub.strip().splitlines())
    header = ("/*\n * File: ota_pubkey.h\n * Purpose: Public key that over-the-air updates must be signed with (ota.h).\n"
              " * Generated by tools/ota_release.py keygen. The private key is NOT in the repository.\n */\n"
              "#pragma once\n\nstatic const char OTA_PUBLIC_KEY_PEM[] =\n" + lines.rstrip("\n") + ";\n")
    open(os.path.join(SKETCH, "ota_pubkey.h"), "w", encoding="utf-8").write(header)
    print(f"Privater Schlüssel: {KEY}  (sichern!)")
    print("Öffentlicher Schlüssel: FitDashboard/ota_pubkey.h")


def secret_values():
    try:
        text = open(os.path.join(SKETCH, "secrets.h"), encoding="utf-8").read()
    except OSError:
        return []
    return [v for v in re.findall(r'#define\s+SECRET_\w+\s+"([^"]*)"', text) if len(v) >= 4]


def build():
    cli = os.environ.get("ARDUINO_CLI") or shutil.which("arduino-cli")
    if not cli:
        sys.exit("arduino-cli nicht gefunden (PATH oder $ARDUINO_CLI)")
    out = os.path.join(OUT, "build")
    cmd = [cli, *shlex.split(os.environ.get("ARDUINO_CLI_ARGS", "")), "compile", "--fqbn", FQBN, "--build-path", out,
           "--build-property", "compiler.cpp.extra_flags=-DFITDASH_RELEASE", SKETCH]
    subprocess.run(cmd, check=True)
    release(os.path.join(out, "FitDashboard.ino.bin"))


def release(binary):
    data = open(binary, "rb").read()
    leaked = [v for v in secret_values() if v.encode() in data]
    if leaked:
        sys.exit("ABBRUCH: Die Firmware enthält Werte aus secrets.h (WLAN/Garmin-Key) und darf nicht veröffentlicht "
                 "werden.\nMit 'ota_release.py build' bauen oder secrets.h beim Kompilieren vorübergehend umbenennen.")
    if data[:1] != b"\xe9":
        sys.exit("Keine ESP32-App-Datei (erstes Byte nicht 0xE9). Gemeint ist FitDashboard.ino.bin, "
                 "nicht .merged.bin oder .bootloader.bin.")
    if len(data) > APP_PARTITION:
        sys.exit(f"Firmware {len(data)} B ist größer als die App-Partition ({APP_PARTITION} B)")
    key = serialization.load_pem_private_key(open(KEY, "rb").read(), password=None)
    sig = key.sign(data, ec.ECDSA(hashes.SHA256()))

    version, build, manifest = define("FW_VERSION"), define("FW_BUILD"), define("OTA_MANIFEST_URL")
    marker = "/releases/latest/download/"
    if marker in manifest:
        url = manifest.split(marker)[0] + f"/releases/download/v{version}/FitDashboard.bin"
    else:
        url = manifest.rsplit("/", 1)[0] + "/FitDashboard.bin"
    os.makedirs(OUT, exist_ok=True)
    shutil.copyfile(binary, os.path.join(OUT, "FitDashboard.bin"))
    info = {"build": build, "version": version, "url": url, "size": len(data),
            "sha256": hashlib.sha256(data).hexdigest(), "sig": base64.b64encode(sig).decode()}
    json.dump(info, open(os.path.join(OUT, "version.json"), "w"), indent=1)
    print(f"Version {version} (Build {build}), {len(data)} B")
    print(f"release/FitDashboard.bin + release/version.json -> GitHub-Release mit Tag v{version} hochladen")
    print(f"Firmware-URL im Manifest: {url}")


if __name__ == "__main__":
    if len(sys.argv) == 2 and sys.argv[1] == "keygen":
        keygen()
    elif len(sys.argv) == 2 and sys.argv[1] == "build":
        build()
    elif len(sys.argv) == 3 and sys.argv[1] == "release":
        release(sys.argv[2])
    else:
        sys.exit(__doc__)
